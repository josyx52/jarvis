def _agentless_run(machine: str, script: str, machine_type: str = "workstation", timeout_s: int = 60) -> tuple[str, str]:
    """
    Executa um script PowerShell numa máquina sem agente via WinRM.
    Executa um script PowerShell numa máquina remota via WinRM.
    """
    import config as _cfg
    center_url = _cfg.center_api_url() or os.getenv("JARVIS_CENTER_URL", "http://localhost:8080")
    api_key    = _cfg.center_api_key() or os.getenv("JARVIS_API_KEY", "")
    timeout_s  = max(10, min(int(timeout_s), 120))

    try:
        resp = _requests.post(
            f"{center_url}/agentless/execute",
            json={
                "machine":      machine,
                "script":       script,
                "machine_type": machine_type,
                "timeout_s":    timeout_s,
            },
            headers={"X-API-Key": api_key},
            timeout=timeout_s + 30,
        )
        resp.raise_for_status()
        data = resp.json()
        result = {
            "machine":   data.get("machine"),
            "exit_code": data.get("exit_code"),
            "stdout":    (data.get("stdout") or "").strip(),
            "stderr":    (data.get("stderr") or "").strip(),
            "ok":        data.get("ok", False),
        }
        label = f"agentless_run host={machine}"
        return json.dumps(result, ensure_ascii=False), label

    except _requests.exceptions.Timeout:
        return json.dumps({
            "machine":   machine,
            "exit_code": -2,
            "stdout":    "",
            "stderr":    f"WinRM não respondeu em {timeout_s + 30}s. Verificar se a máquina está online e acessível.",
            "ok":        False,
        }), f"agentless_run host={machine} TIMEOUT"
    except Exception as e:
        return json.dumps({"error": str(e), "machine": machine}), ""


