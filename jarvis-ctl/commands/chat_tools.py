def _manage_webhook(
    action: str,
    url: str = "",
    name: str = "",
    min_severity: str = "high",
    host_filter: str = "",
) -> tuple[str, str]:
    """Gere webhooks de notificação do Solution Driver."""
    try:
        conn = get_db()
        cur = conn.cursor()

        if action == "list":
            cur.execute(
                "SELECT id, name, url, min_severity, host_filter, active, created_at "
                "FROM notification_webhooks ORDER BY created_at DESC"
            )
            cols = [d[0] for d in cur.description]
            rows = [_ts(dict(zip(cols, r)), "created_at") for r in cur.fetchall()]
            return json.dumps({"webhooks": rows, "total": len(rows)}, default=str), \
                   "SELECT * FROM notification_webhooks"

        if not url:
            return json.dumps({"error": "url é obrigatório para esta acção"}), ""

        if action == "add":
            host_list = [h.strip() for h in host_filter.split(",") if h.strip()] or None
            cur.execute(
                """
                INSERT INTO notification_webhooks (name, url, min_severity, host_filter, active)
                VALUES (%s, %s, %s, %s, TRUE)
                ON CONFLICT DO NOTHING
                RETURNING id
                """,
                (name or url, url, min_severity, host_list),
            )
            conn.commit()
            row = cur.fetchone()
            if not row:
                return json.dumps({"added": False, "message": "URL já existe"}), ""

            # Teste imediato ao endpoint
            endpoint_ok   = False
            endpoint_msg  = ""
            try:
                resp = _requests.post(
                    url,
                    json={"type": "jarvis_health_check", "version": "1.0"},
                    timeout=5,
                )
                endpoint_ok  = True
                endpoint_msg = f"Endpoint respondeu com HTTP {resp.status_code}."
            except Exception as ex:
                endpoint_msg = f"Endpoint não respondeu: {ex}"

            return json.dumps({
                "added":          True,
                "id":             row[0],
                "url":            url,
                "min_severity":   min_severity,
                "endpoint_ok":    endpoint_ok,
                "endpoint_check": endpoint_msg,
                "message": (
                    f"Webhook registado. {endpoint_msg} "
                    f"O Jarvis enviará notificações para '{url}' "
                    f"quando detectar problemas de severidade >= {min_severity}. "
                    "O payload inclui um callback_url para o analista responder."
                ) if endpoint_ok else (
                    f"Webhook registado mas o endpoint não está acessível: {endpoint_msg} "
                    "Verifica a URL e garante que o servidor está a aceitar POST. "
                    "O Solution Driver só dispara se o endpoint responder no momento do alerta."
                ),
            }), ""

        if action in ("enable", "disable"):
            active = action == "enable"
            cur.execute(
                "UPDATE notification_webhooks SET active=%s WHERE url=%s RETURNING id",
                (active, url),
            )
            conn.commit()
            row = cur.fetchone()
            if row:
                return json.dumps({"updated": True, "url": url, "active": active}), ""
            return json.dumps({"error": "Webhook não encontrado"}), ""

        if action == "remove":
            cur.execute(
                "DELETE FROM notification_webhooks WHERE url=%s RETURNING id", (url,)
            )
            conn.commit()
            row = cur.fetchone()
            if row:
                return json.dumps({"removed": True, "url": url}), ""
            return json.dumps({"error": "Webhook não encontrado"}), ""

        return json.dumps({"error": f"Acção desconhecida: {action}"}), ""

    except Exception as e:
        try: get_db().rollback()
        except Exception: pass
        return json.dumps({"error": str(e)}), ""


