def _analyze_time_pattern(host: str, event_type: str | None = None, days_back: int = 30) -> tuple[str, str]:
    """
    Agrupa eventos históricos por hora-do-dia e dia-da-semana para detectar padrões recorrentes.
    Retorna os top padrões com contagem de ocorrências.
    """
    conn = get_db()
    cur  = conn.cursor()
    try:
        params: list = [f"%{host}%", int(days_back)]
        type_filter  = ""
        if event_type:
            type_filter = "AND event_type = %s"
            params.append(event_type)

        cur.execute(
            f"""
            SELECT
                event_type,
                EXTRACT(HOUR  FROM created_at)::INT  AS hour_of_day,
                EXTRACT(DOW   FROM created_at)::INT  AS day_of_week,
                COUNT(*)                             AS occurrences
            FROM events
            WHERE host ILIKE %s
              AND created_at > NOW() - INTERVAL '%s days'
              {type_filter}
            GROUP BY event_type, hour_of_day, day_of_week
            HAVING COUNT(*) >= 2
            ORDER BY occurrences DESC
            LIMIT 40
            """,
            params,
        )
        cols = [d[0] for d in cur.description]
        rows = [dict(zip(cols, r)) for r in cur.fetchall()]

        # Enriquecer com nome do dia da semana
        dow_names = {0: "Sunday", 1: "Monday", 2: "Tuesday", 3: "Wednesday",
                     4: "Thursday", 5: "Friday", 6: "Saturday"}
        for r in rows:
            r["day_name"] = dow_names.get(r.get("day_of_week", -1), "?")

        summary = {
            "host":     host,
            "days_analysed": days_back,
            "patterns": rows,
            "total_patterns_found": len(rows),
        }
        return json.dumps(summary, default=str), f"time_pattern host ILIKE '%{host}%' last {days_back}d"
    except Exception as e:
        try: conn.rollback()
        except Exception: pass
        return json.dumps({"error": str(e)}), ""


