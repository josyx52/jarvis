def _query_security_events(host: str = "", since_minutes: int = 1440, include_ueba: bool = True) -> tuple[str, str]:
    """
    Investigação de segurança contextual: para cada utilizador/host envolvido, enriquece
    com o perfil comportamental guardado (horários típicos, função, apps) e o perfil da
    máquina (serviços críticos, papel, impacto). Sem listas estáticas — todo o contexto
    vem dos dados recolhidos pelo Jarvis.
    """
    conn = get_db()
    cur  = conn.cursor()
    try:
        # 1. Eventos de segurança recentes
        security_types = (
            "discovery_change", "network_throughput_spike", "service_stopped",
            "login_failed", "privilege_escalation", "unauthorized_access",
            "new_listening_port", "process_anomaly", "lateral_movement",
        )
        placeholders = ",".join(["%s"] * len(security_types))
        ev_where = [
            f"created_at >= NOW() - INTERVAL '{int(since_minutes)} minutes'",
            f"event_type IN ({placeholders})",
        ]
        ev_params: list = list(security_types)
        if host:
            ev_where.append("host ILIKE %s")
            ev_params.append(f"%{host}%")
        cur.execute(
            f"SELECT host, event_type, severity, summary, payload, created_at "
            f"FROM events WHERE {' AND '.join(ev_where)} ORDER BY created_at DESC LIMIT 50",
            ev_params,
        )
        cols = [d[0] for d in cur.description]
        events = [_ts(dict(zip(cols, r)), "created_at") for r in cur.fetchall()]

        # Hosts únicos envolvidos
        affected_hosts = list({e["host"] for e in events})

        # 2. UEBA — análises suspeitas/high_risk (janela alargada: 7 dias)
        ueba_entries = []
        if include_ueba:
            ueba_where = [
                f"analyzed_at >= NOW() - INTERVAL '{min(int(since_minutes) * 7, 10080)} minutes'",
                "verdict IN ('suspicious','high_risk')",
            ]
            ueba_params: list = []
            if host:
                ueba_where.append("host ILIKE %s")
                ueba_params.append(f"%{host}%")
            cur.execute(
                f"""SELECT host, username, compliance_score, verdict,
                           summary, anomalies, events_analyzed, analyzed_at
                    FROM ueba_analyses
                    WHERE {' AND '.join(ueba_where)}
                    ORDER BY compliance_score ASC LIMIT 25""",
                ueba_params,
            )
            cols = [d[0] for d in cur.description]
            ueba_entries = [_ts(dict(zip(cols, r)), "analyzed_at") for r in cur.fetchall()]
            for e in ueba_entries:
                if e["host"] not in affected_hosts:
                    affected_hosts.append(e["host"])

        # Utilizadores únicos presentes nas análises UEBA
        unique_users = list({e["username"] for e in ueba_entries if e.get("username")})

        # 3. Enriquecimento: perfil comportamental de cada utilizador
        user_context: dict = {}
        if unique_users:
            user_placeholders = ",".join(["%s"] * len(unique_users))
            cur.execute(
                f"""SELECT host, username, is_human, risk_score, risk_level, risk_delta,
                           work_type, primary_apps, typical_hours, active_days,
                           after_hours_activity, weekend_activity,
                           privilege_abuse_detected, behavioral_anomalies, summary
                    FROM user_profiles
                    WHERE username IN ({user_placeholders})
                    ORDER BY risk_score DESC""",
                unique_users,
            )
            cols = [d[0] for d in cur.description]
            for r in cur.fetchall():
                row_d = dict(zip(cols, r))
                key = (row_d["username"], row_d["host"])
                user_context[key] = row_d
                # Guardar também só por username para lookup cruzado
                if row_d["username"] not in user_context:
                    user_context[row_d["username"]] = row_d

        # Injectar contexto do utilizador em cada entrada UEBA
        for entry in ueba_entries:
            uname = entry.get("username", "")
            hname = entry.get("host", "")
            profile = user_context.get((uname, hname)) or user_context.get(uname)
            if profile:
                entry["user_profile"] = {
                    "is_human":            profile.get("is_human"),
                    "work_type":           profile.get("work_type"),
                    "typical_hours":       profile.get("typical_hours"),
                    "active_days":         profile.get("active_days"),
                    "after_hours_activity":profile.get("after_hours_activity"),
                    "weekend_activity":    profile.get("weekend_activity"),
                    "risk_score":          profile.get("risk_score"),
                    "risk_level":          profile.get("risk_level"),
                    "risk_delta":          profile.get("risk_delta"),
                    "primary_apps":        profile.get("primary_apps"),
                    "privilege_abuse":     profile.get("privilege_abuse_detected"),
                    "behavioral_anomalies":profile.get("behavioral_anomalies"),
                    "profile_summary":     profile.get("summary"),
                }
            else:
                entry["user_profile"] = None  # sem dados históricos sobre este utilizador

        # 4. Enriquecimento: perfil de cada host afectado (serviços críticos, papel, impacto)
        machine_context: dict = {}
        if affected_hosts:
            host_placeholders = ",".join(["%s"] * len(affected_hosts))
            # host na DB pode ter sufixo ::uuid — usar ILIKE para cada host
            for ah in affected_hosts:
                ah_base = ah.split("::")[0]
                cur.execute(
                    "SELECT host, profile FROM server_profiles WHERE host ILIKE %s LIMIT 1",
                    (f"%{ah_base}%",),
                )
                row = cur.fetchone()
                if row:
                    prof = row[1] if isinstance(row[1], dict) else json.loads(row[1])
                    machine_context[ah] = {
                        "role":              prof.get("role"),
                        "env":               prof.get("env"),
                        "business_impact":   prof.get("business_impact"),
                        "critical_services": prof.get("critical_services", []),
                        "important_services":prof.get("important_services", []),
                        "tech_stack":        prof.get("tech_stack", []),
                        "risk_flags":        prof.get("risk_flags", []),
                        "role_detail":       prof.get("role_detail"),
                    }

        # 5. Problemas abertos nos hosts afectados
        open_problems = []
        if affected_hosts:
            for ah in affected_hosts:
                ah_base = ah.split("::")[0]
                cur.execute(
                    """SELECT problem_id, host, title, severity, alert_count, opened_at
                       FROM problems
                       WHERE host ILIKE %s AND status='open'
                       ORDER BY alert_count DESC LIMIT 3""",
                    (f"%{ah_base}%",),
                )
                cols = [d[0] for d in cur.description]
                for r in cur.fetchall():
                    open_problems.append(_ts(dict(zip(cols, r)), "opened_at"))

        return json.dumps({
            "security_events": events,
            "ueba_findings":   ueba_entries,
            "machine_profiles": machine_context,
            "open_problems":   open_problems,
            "summary": {
                "total_security_events": len(events),
                "ueba_suspicious_users": len({e["username"] for e in ueba_entries}),
                "affected_hosts":        len(affected_hosts),
                "hosts_with_profile":    len(machine_context),
                "open_problems":         len(open_problems),
            },
            "investigation_guide": (
                "Para cada utilizador em ueba_findings: consulta user_profile (típico vs actual). "
                "Para cada host: consulta machine_profiles (serviços críticos em risco?). "
                "Para cada open_problem: está relacionado com este utilizador/evento? "
                "Contas de sistema Windows (DWM-N, UMFD-N, Font Driver Host, NT AUTHORITY) "
                "têm comportamento de logon/logoff curto por design — verificar com agentless_run "
                "antes de escalar. Utilizadores sem user_profile são desconhecidos pelo Jarvis — "
                "investigar com agentless_run quem são e o que estavam a fazer."
            ),
        }, default=str), f"security_events + ueba + user_profiles + machine_profiles (last {since_minutes}m)"
    except Exception as e:
        try: conn.rollback()
        except Exception: pass
        return json.dumps({"error": str(e)}), ""


def _manage_authorized_users(action: str, username: str = "", reason: str = "") -> tuple[str, str]:
    """Gere a lista de utilizadores autorizados para o sistema UEBA."""
    conn = get_db()
    cur  = conn.cursor()
    try:
        cur.execute("SELECT value FROM jarvis_config WHERE key='ueba.authorized_users'")
        row = cur.fetchone()
        current: list = []
        if row and row[0]:
            try:
                current = json.loads(row[0]) if row[0].startswith("[") else [u.strip() for u in row[0].split(",") if u.strip()]
            except Exception:
                current = []

        if action == "list":
            return json.dumps({
                "authorized_users": current,
                "count": len(current),
                "message": (
                    f"{len(current)} utilizador(es) autorizado(s) configurado(s). "
                    "O UEBA sinaliza estes utilizadores com contexto 'autorizado' em vez de alarme directo."
                    if current else
                    "Nenhum utilizador autorizado configurado ainda. "
                    "Usa manage_authorized_users action='add' username='DOMINIO\\\\utilizador'."
                ),
            }), "jarvis_config ueba.authorized_users"

        if not username:
            return json.dumps({"error": "username é obrigatório para add/remove"}), ""

        if action == "add":
            if username not in current:
                current.append(username)
            cur.execute(
                """INSERT INTO jarvis_config (key, value, type, category, description, updated_at)
                   VALUES ('ueba.authorized_users', %s, 'json', 'ueba', 'Utilizadores autorizados (sem alerta UEBA)', NOW())
                   ON CONFLICT (key) DO UPDATE SET value=EXCLUDED.value, updated_at=NOW()""",
                (json.dumps(current),),
            )
            conn.commit()
            return json.dumps({
                "added": username,
                "authorized_users": current,
                "message": f"'{username}' adicionado à lista de utilizadores autorizados. O UEBA não vai escalar alertas deste utilizador sem evidência adicional.",
            }), ""

        if action == "remove":
            before = len(current)
            current = [u for u in current if u != username]
            cur.execute(
                """INSERT INTO jarvis_config (key, value, type, category, description, updated_at)
                   VALUES ('ueba.authorized_users', %s, 'json', 'ueba', 'Utilizadores autorizados (sem alerta UEBA)', NOW())
                   ON CONFLICT (key) DO UPDATE SET value=EXCLUDED.value, updated_at=NOW()""",
                (json.dumps(current),),
            )
            conn.commit()
            removed = before != len(current)
            return json.dumps({
                "removed": removed,
                "authorized_users": current,
                "message": f"'{username}' {'removido da' if removed else 'não encontrado na'} lista de utilizadores autorizados.",
            }), ""

        return json.dumps({"error": f"Acção desconhecida: {action}"}), ""
    except Exception as e:
        try: conn.rollback()
        except Exception: pass
        return json.dumps({"error": str(e)}), ""


def _build_machine_profiles(host: str = "") -> tuple[str, str]:
    """Dispara a construção/actualização de perfis de máquina com base nos dados existentes na DB."""
    import subprocess, sys, os
    script = os.path.join(
        os.path.dirname(os.path.dirname(os.path.dirname(__file__))),
        "jarvis_center", "engines", "machine_profile_engine.py"
    )
    if not os.path.exists(script):
        return json.dumps({"error": f"MachineProfileEngine não encontrado em {script}"}), ""
    try:
        args = [sys.executable, script]
        if host:
            args += ["--host", host]
        r = subprocess.run(args, capture_output=True, text=True, timeout=120,
                           cwd=os.path.dirname(script))
        return json.dumps({
            "launched": True,
            "stdout": r.stdout[-2000:] if r.stdout else "",
            "stderr": r.stderr[-500:]  if r.stderr else "",
            "returncode": r.returncode,
        }), "machine_profile_engine"
    except Exception as e:
        return json.dumps({"error": str(e)}), ""
