def _run_cmd(args: list[str]) -> tuple[int, str, str]:
    """Corre um comando e devolve (returncode, stdout, stderr)."""
    try:
        r = __import__("subprocess").run(
            args, capture_output=True, text=True, timeout=15,
            creationflags=0x08000000,  # CREATE_NO_WINDOW
        )
        return r.returncode, r.stdout.strip(), r.stderr.strip()
    except Exception as e:
        return -1, "", str(e)


def _svc_state() -> str | None:
    """Devolve o estado do serviço Windows ou None se não existir."""
    rc, out, _ = _run_cmd(["sc", "query", _SVC_NAME])
    if rc != 0:
        return None
    for line in out.splitlines():
        if "STATE" in line:
            parts = line.split()
            # ex: "STATE              : 4  RUNNING"
            for i, p in enumerate(parts):
                if p in ("RUNNING", "STOPPED", "PAUSED", "START_PENDING", "STOP_PENDING"):
                    return p
    return "UNKNOWN"


