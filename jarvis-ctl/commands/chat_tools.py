def execute_tool(name: str, args: dict) -> tuple[str, str]:
    """Execute a tool. Returns (result_json, sql_summary)."""
    try:
        dispatch = {
            "query_problems":                    _query_problems,
            "query_events":                      _query_events,
            "query_agents":                      _query_agents,
            "query_metrics":                     _query_metrics,
            "query_alerts":                      _query_alerts,
            "get_config":                        _get_config,
            "query_instrumentation_coverage":    _query_instrumentation_coverage,
            "query_instrumentation_recommendations": _query_instrumentation_recommendations,
            "request_instrumentation":           _request_instrumentation,
            "agentless_run":                     _agentless_run,
            "analyze_time_pattern":              _analyze_time_pattern,
            "query_machine_profile":             _query_machine_profile,
            "build_machine_profiles":            _build_machine_profiles,
            "query_user_profiles":               _query_user_profiles,
            "query_ueba":                        _query_ueba,
            "query_reasoning":                   _query_reasoning,
            "query_security_events":             _query_security_events,
            "manage_authorized_users":           _manage_authorized_users,
            "manage_center":                      _manage_center,
            "manage_webhook":                    _manage_webhook,
            "manage_solution_engine":            _manage_solution_engine,
            "list_conversations":                _list_conversations,
            "get_conversation":                  _get_conversation,
        }
        fn = dispatch.get(name)
        if fn is None:
            return json.dumps({"error": f"Unknown tool: {name}"}), ""
        return fn(**args)
    except Exception as e:
        # Rollback para não deixar a transacção num estado abortado que bloqueia queries seguintes
        try:
            get_db().rollback()
        except Exception:
            pass
        return json.dumps({"error": str(e)}), ""


def _ts(row: dict, *keys):
    for k in keys:
        if row.get(k):
            row[k] = str(row[k])
    return row


def _query_problems(status="all", host=None, limit=10):
    conn = get_db()
    cur  = conn.cursor()
    where, params = [], []
    if status != "all":
        where.append("status = %s"); params.append(status)
    if host:
        where.append("host ILIKE %s"); params.append(f"%{host}%")
    w   = ("WHERE " + " AND ".join(where)) if where else ""
    sql = f"SELECT problem_id, host, title, severity, status, alert_count, opened_at, last_seen, duration_s FROM problems {w} ORDER BY opened_at DESC LIMIT %s"
    params.append(limit)
    cur.execute(sql, params)
    cols = [d[0] for d in cur.description]
    rows = [_ts(dict(zip(cols, r)), "opened_at", "last_seen") for r in cur.fetchall()]
    return json.dumps(rows, default=str), f"problems {w} LIMIT {limit}"


def _query_events(host=None, event_type=None, severity=None, since_minutes=60, limit=20):
    conn = get_db()
    cur  = conn.cursor()
    where  = [f"created_at >= NOW() - INTERVAL '{int(since_minutes)} minutes'"]
    params = []
    if host:        where.append("host ILIKE %s");       params.append(f"%{host}%")
    if event_type:  where.append("event_type = %s");     params.append(event_type)
    if severity:    where.append("severity = %s");       params.append(severity)
    w   = "WHERE " + " AND ".join(where)
    sql = f"SELECT host, event_type, severity, summary, created_at FROM events {w} ORDER BY created_at DESC LIMIT %s"
    params.append(limit)
    cur.execute(sql, params)
    cols = [d[0] for d in cur.description]
    rows = [_ts(dict(zip(cols, r)), "created_at") for r in cur.fetchall()]
    return json.dumps(rows, default=str), f"events (last {since_minutes}m) LIMIT {limit}"


def _query_agents(active_only=False):
    conn = get_db()
    cur  = conn.cursor()
    if active_only:
        sql = "SELECT host, TO_TIMESTAMP(MAX(snapshot_time)) AS last_seen FROM snapshots WHERE snapshot_time >= EXTRACT(EPOCH FROM NOW() - INTERVAL '5 minutes') GROUP BY host ORDER BY last_seen DESC"
    else:
        sql = "SELECT host, TO_TIMESTAMP(MAX(snapshot_time)) AS last_seen FROM snapshots GROUP BY host ORDER BY last_seen DESC"
    cur.execute(sql)
    cols = [d[0] for d in cur.description]
    rows = [_ts(dict(zip(cols, r)), "last_seen") for r in cur.fetchall()]
    return json.dumps(rows, default=str), sql


def _query_metrics(host, since_minutes=60):
    # snapshot_time é DOUBLE PRECISION (epoch Unix) — nunca usar comparação com timestamptz
    conn = get_db()
    cur  = conn.cursor()
    cur.execute(
        """
        SELECT snapshot_time, cpu_percent, memory_percent, disk_percent
          FROM snapshots
         WHERE host ILIKE %s
           AND snapshot_time >= EXTRACT(EPOCH FROM NOW() - INTERVAL %s)
         ORDER BY snapshot_time DESC
         LIMIT 60
        """,
        (f"%{host}%", f"{int(since_minutes)} minutes"),
    )
    cols = [d[0] for d in cur.description]
    rows = [dict(zip(cols, r)) for r in cur.fetchall()]
    return json.dumps(rows, default=str), f"snapshots WHERE host ILIKE '%{host}%' (last {since_minutes}m)"


