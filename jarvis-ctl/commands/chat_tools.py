def _query_instrumentation_coverage(host, since_minutes=30):
    conn = get_db()
    cur  = conn.cursor()

    # Processos conhecidos do último snapshot
    cur.execute("""
        SELECT raw_json FROM snapshots
        WHERE host ILIKE %s ORDER BY snapshot_time DESC LIMIT 1
    """, [f"%{host}%"])
    row = cur.fetchone()
    processes = []
    if row and row[0]:
        import json as _json
        snap = _json.loads(row[0]) if isinstance(row[0], str) else row[0]
        processes = snap.get("processes") or []

    # Serviços que produziram traces recentemente
    cur.execute("""
        SELECT DISTINCT payload->>'service' AS service
        FROM traces
        WHERE host ILIKE %s
          AND recorded_at >= NOW() - INTERVAL '%s minutes'
          AND payload->>'service' IS NOT NULL
        LIMIT 50
    """, [f"%{host}%", int(since_minutes)])
    traced = {r[0] for r in cur.fetchall() if r[0]}

    # Cruzar
    proc_names = {(p.get("name") or "").lower().replace(".exe", "") for p in processes}
    instrumented   = sorted(traced & proc_names)
    not_instrumented = sorted(proc_names - traced - {""})

    result = {
        "instrumented_services": list(traced),
        "running_processes_not_traced": not_instrumented[:20],
        "coverage_pct": round(len(instrumented) / max(len(proc_names), 1) * 100, 1),
    }
    return json.dumps(result), f"traces + snapshots WHERE host ILIKE '%{host}%'"


