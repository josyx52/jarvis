def _tail_file(path: str, n: int) -> list[str]:
    if not os.path.exists(path):
        return []
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            return f.readlines()[-n:]
    except Exception:
        return []


def _manage_center(action: str, lines: int = 50) -> tuple[str, str]:
    svc = _svc_state()  # None = não instalado como serviço

    # ── STATUS ────────────────────────────────────────────────────────────────
    if action == "status":
        api_ok,   api_msg   = _api_health()
        redis_ok, redis_msg = _redis_health()
        db_ok,    db_msg    = _db_health()

        if svc is not None:
            center_running = svc == "RUNNING"
            center_info    = f"Serviço Windows ({_SVC_NAME}): {svc}"
        else:
            # Verificar processo python start_center.py
            rc, out, _ = _run_cmd(
                ["tasklist", "/FI", "IMAGENAME eq python.exe", "/FO", "CSV", "/NH"]
            )
            # Heurística: API a responder significa center a correr
            center_running = api_ok
            center_info    = "Processo standalone (sem serviço Windows)"

        return json.dumps({
            "center": {
                "running": center_running,
                "info":    center_info,
            },
            "api":   {"ok": api_ok,   "detail": api_msg},
            "redis": {"ok": redis_ok, "detail": redis_msg},
            "db":    {"ok": db_ok,    "detail": db_msg},
            "summary": (
                "ONLINE — todos os componentes a funcionar"
                if center_running and api_ok and redis_ok and db_ok
                else "DEGRADADO — verificar componentes em erro"
            ),
        }), "center status"

    # ── START ─────────────────────────────────────────────────────────────────
    if action == "start":
        if svc is not None:
            if svc == "RUNNING":
                return json.dumps({"message": f"Serviço {_SVC_NAME} já está a correr."}), ""
            rc, out, err = _run_cmd(["net", "start", _SVC_NAME])
            ok = rc == 0 or "already" in out.lower()
            return json.dumps({
                "started": ok,
                "message": f"net start {_SVC_NAME}: {'OK' if ok else err or out}",
            }), ""
        else:
            # Standalone: lança start_center.py em background
            center_dir = _INSTALL_DIR if os.path.isdir(_INSTALL_DIR) else _DEV_DIR
            script     = os.path.join(center_dir, "start_center.py")
            if not os.path.exists(script):
                return json.dumps({"error": f"start_center.py não encontrado em {center_dir}"}), ""
            import subprocess as _sp
            _sp.Popen(
                [sys.executable, script],
                cwd=center_dir,
                creationflags=_sp.CREATE_NEW_CONSOLE,
            )
            return json.dumps({
                "started": True,
                "message": f"Center iniciado como processo standalone em {center_dir}. Aguarda ~5s.",
            }), ""

    # ── STOP ──────────────────────────────────────────────────────────────────
    if action == "stop":
        if svc is not None:
            if svc == "STOPPED":
                return json.dumps({"message": f"Serviço {_SVC_NAME} já está parado."}), ""
            rc, out, err = _run_cmd(["net", "stop", _SVC_NAME])
            ok = rc == 0 or "already" in out.lower()
            return json.dumps({
                "stopped": ok,
                "message": f"net stop {_SVC_NAME}: {'OK' if ok else err or out}",
            }), ""
        else:
            # Standalone: matar processos python com start_center.py na linha de comando
            rc, out, err = _run_cmd([
                "wmic", "process", "where",
                "name='python.exe' and commandline like '%start_center%'",
                "call", "terminate",
            ])
            return json.dumps({
                "stopped": rc == 0,
                "message": "Processos start_center.py terminados." if rc == 0 else (err or out),
            }), ""

    # ── RESTART ───────────────────────────────────────────────────────────────
    if action == "restart":
        if svc is not None:
            _run_cmd(["net", "stop", _SVC_NAME])
            __import__("time").sleep(3)
            rc, out, err = _run_cmd(["net", "start", _SVC_NAME])
            ok = rc == 0
            return json.dumps({
                "restarted": ok,
                "message": f"net stop + net start {_SVC_NAME}: {'OK' if ok else err or out}",
            }), ""
        else:
            # stop + start standalone
            _run_cmd([
                "wmic", "process", "where",
                "name='python.exe' and commandline like '%start_center%'",
                "call", "terminate",
            ])
            __import__("time").sleep(2)
            center_dir = _INSTALL_DIR if os.path.isdir(_INSTALL_DIR) else _DEV_DIR
            script     = os.path.join(center_dir, "start_center.py")
            import subprocess as _sp
            _sp.Popen(
                [sys.executable, script],
                cwd=center_dir,
                creationflags=_sp.CREATE_NEW_CONSOLE,
            )
            return json.dumps({"restarted": True, "message": "Center reiniciado."}), ""

    # ── LOGS ──────────────────────────────────────────────────────────────────
    if action == "logs":
        lines = max(10, min(int(lines), 500))
        if os.path.exists(_LOG_STDOUT):
            tail = _tail_file(_LOG_STDOUT, lines)
            return json.dumps({
                "file":  _LOG_STDOUT,
                "lines": len(tail),
                "content": "".join(tail),
            }), ""
        # Tentar stderr se stdout não existir
        if os.path.exists(_LOG_STDERR):
            tail = _tail_file(_LOG_STDERR, lines)
            return json.dumps({
                "file":  _LOG_STDERR,
                "lines": len(tail),
                "content": "".join(tail),
            }), ""
        return json.dumps({
            "message": (
                f"Ficheiros de log não encontrados em {_INSTALL_DIR}\\logs\\. "
                "Se o center correu em modo standalone (terminal), os logs ficam no stdout do processo."
            )
        }), ""

    return json.dumps({"error": f"Acção desconhecida: {action}"}), ""


